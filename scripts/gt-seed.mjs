function sqlString(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insertRow({ id, form, status, data, email, name, fileKey, fileName, fileSize, createdAt, notes }) {
  const values = [
    sqlString(id),
    sqlString(form),
    sqlString(status),
    sqlString(JSON.stringify(data)),
    sqlString(email ?? null),
    sqlString(name ?? null),
    sqlString(fileKey ?? null),
    sqlString(fileName ?? null),
    fileSize ?? "NULL",
    sqlString(createdAt),
    sqlString(createdAt),
    sqlString(notes ?? null),
  ];
  return `INSERT INTO submissions (id, form, status, data, email, name, file_key, file_name, file_size, created_at, updated_at, notes) VALUES (${values.join(", ")});`;
}

